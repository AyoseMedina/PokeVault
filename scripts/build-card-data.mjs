// Generates dist/card-data.js (base stats 1–649 and move type/power/PP per
// generation) from PokéAPI CSVs at the same pinned revision as the Pokédex.
// Run: node scripts/build-card-data.mjs
import { mkdir, readFile, writeFile } from 'node:fs/promises';

const REVISION = 'e5b79b2e15d7c50735a945936afd4cd1cfd94eae';
const CACHE = new URL(`../.test-output/pokedex-data/${REVISION}/`, import.meta.url);
const MAX_SPECIES = 649, MAX_MOVE = 559;

async function csv(name) {
  await mkdir(CACHE, { recursive: true });
  const path = new URL(name, CACHE);
  let text;
  try { text = await readFile(path, 'utf8'); }
  catch {
    const response = await fetch(`https://raw.githubusercontent.com/PokeAPI/pokeapi/${REVISION}/data/v2/csv/${name}`);
    if (!response.ok) throw new Error(`${response.status} ${name}`);
    text = await response.text(); await writeFile(path, text);
  }
  const [header, ...rows] = text.trim().split(/\r?\n/).map(line => line.split(','));
  return rows.map(row => Object.fromEntries(header.map((key, i) => [key, row[i]])));
}
const num = v => v === '' || v === undefined ? null : Number(v);

// Base stats: hp, attack, defense, special-attack, special-defense, speed (stat ids 1–6).
const stats = Array.from({ length: MAX_SPECIES + 1 }, () => null);
for (const row of await csv('pokemon_stats.csv')) {
  const id = Number(row.pokemon_id), stat = Number(row.stat_id);
  if (id < 1 || id > MAX_SPECIES || stat < 1 || stat > 6) continue;
  (stats[id] ||= [0, 0, 0, 0, 0, 0])[stat - 1] = Number(row.base_stat);
}
for (let i = 1; i <= MAX_SPECIES; i++) if (!stats[i] || stats[i].some(n => !n)) throw new Error(`stats ${i}`);

// Moves: current values, then the per-generation value from move_changelog.csv
// (each row holds the value used BEFORE changed_in_version_group).
const generationOf = Object.fromEntries((await csv('version_groups.csv')).map(r => [r.id, Number(r.generation_id)]));
const current = {};
for (const row of await csv('moves.csv')) {
  const id = Number(row.id); if (id < 1 || id > MAX_MOVE) continue;
  current[id] = { type: num(row.type_id), power: num(row.power), pp: num(row.pp), damageClass: num(row.damage_class_id) };
}
const changes = (await csv('move_changelog.csv')).filter(r => Number(r.move_id) <= MAX_MOVE)
  .map(r => ({ id: Number(r.move_id), gen: generationOf[r.changed_in_version_group_id], type: num(r.type_id), power: num(r.power), pp: num(r.pp) }))
  .sort((a, b) => a.gen - b.gen);
const moves = {};
for (let g = 1; g <= 5; g++) {
  moves[g] = Array.from({ length: MAX_MOVE + 1 }, (_, id) => {
    const base = current[id]; if (!base) return null;
    const value = { ...base };
    // Walk changes from newest to oldest that happened after generation g.
    for (const change of changes.filter(c => c.id === id && c.gen > g).reverse()) {
      if (change.type !== null) value.type = change.type;
      if (change.power !== null) value.power = change.power;
      if (change.pp !== null) value.pp = change.pp;
    }
    return [value.type, value.power ?? 0, value.pp ?? 0];
  });
}
// Species: pre-evolution, genus (Spanish, English fallback), height (dm) and weight (hg).
const parent = Array(MAX_SPECIES + 1).fill(0), genus = Array(MAX_SPECIES + 1).fill(''), size = Array(MAX_SPECIES + 1).fill(null);
for (const row of await csv('pokemon_species.csv')) { const id = Number(row.id); if (id >= 1 && id <= MAX_SPECIES) parent[id] = num(row.evolves_from_species_id) || 0; }
const genusRows = await csv('pokemon_species_names.csv');
for (const lang of ['9', '7']) for (const row of genusRows) { const id = Number(row.pokemon_species_id); if (id >= 1 && id <= MAX_SPECIES && row.local_language_id === lang && row.genus) genus[id] = row.genus; }
for (const row of await csv('pokemon.csv')) { const id = Number(row.id); if (id >= 1 && id <= MAX_SPECIES) size[id] = [Number(row.height), Number(row.weight)]; }
for (let i = 1; i <= MAX_SPECIES; i++) if (!genus[i] || !size[i]) throw new Error(`species data ${i}`);
// Type chart per generation, types 1–17 (no Fairy before Gen VI). Base: PokéAPI type_efficacy
// (current); then the documented Gen II–V and Gen I differences.
const chart = Array.from({ length: 18 }, () => Array(18).fill(100));
for (const row of await csv('type_efficacy.csv')) { const a = Number(row.damage_type_id), d = Number(row.target_type_id); if (a <= 17 && d <= 17) chart[a][d] = Number(row.damage_factor); }
const charts = {};
for (let g = 1; g <= 5; g++) {
  const c = chart.map(r => r.slice());
  c[8][9] = 50; c[17][9] = 50;                  // Gen II–V: Steel resists Ghost and Dark (changed in Gen VI).
  if (g === 1) { c[8][14] = 0; c[7][4] = 200; c[4][7] = 200; c[15][10] = 100; } // Gen I: Ghost→Psychic 0, Bug⇄Poison ×2, Ice→Fire ×1.
  charts[g] = c;
}
const out = `// Generated by scripts/build-card-data.mjs from PokéAPI ${REVISION}. Do not edit.
// stats[species] = [HP, Atk, Def, SpA, SpD, Spe] (current base stats, PokéAPI).
// moves[generation][move] = [typeId, power (0 = status/variable), pp] as in that generation.
// parent[species] = pre-evolution (0 = none); genus[species] (es, en fallback); size[species] = [dm, hg].
// charts[generation][attackType][defenseType] = damage factor ×100 (types 1–17).
export const CARD_DATA=${JSON.stringify({ source: `PokéAPI ${REVISION}`, stats, moves, parent, genus, size, charts })};
`;
await writeFile(new URL('../dist/card-data.js', import.meta.url), out);
console.log(`card-data: ${MAX_SPECIES} species, ${MAX_MOVE} moves × 5 generations, ${(out.length / 1024).toFixed(0)} KiB`);
