"""Rebuild offline descriptions from pinned PokeAPI CSVs. Python standard library only."""
import csv
import io
import json
import re
from pathlib import Path
from urllib.request import Request, urlopen

REVISION = 'e5b79b2e15d7c50735a945936afd4cd1cfd94eae'
ROOT = Path(__file__).resolve().parent.parent
CACHE = ROOT / '.test-output' / 'pokedex-data' / REVISION
GAMES = {'yellow':151,'crystal':251,'ruby':386,'sapphire':386,'emerald':386,
         'firered':386,'leafgreen':386,'diamond':493,'pearl':493,'platinum':493,
         'heartgold':493,'soulsilver':493,'black':649,'white':649,'black2':649,'white2':649}
# PokeAPI has no Spanish flavor text for any generation I-V game (Spanish starts
# with X/Y). The user authorized (2026-11-03) Spanish text from a later official
# game, always labelled with that game; English stays the exact edition.
# Each chain is tried in order; X covers every species up to 649.
SPANISH_FROM = {
    'yellow':['letsgopikachu'], 'firered':['letsgopikachu','omegaruby','x'],
    'leafgreen':['letsgoeevee','alphasapphire','y'], 'crystal':['x'],
    'ruby':['omegaruby','x'], 'sapphire':['alphasapphire','y'], 'emerald':['omegaruby','x'],
    'diamond':['x'], 'pearl':['y'], 'platinum':['x'], 'heartgold':['x'], 'soulsilver':['y'],
    'black':['x'], 'white':['y'], 'black2':['x'], 'white2':['y'],
}
SPANISH_GAMES = sorted({g for chain in SPANISH_FROM.values() for g in chain})
MAX_SPECIES = max(GAMES.values())

def rows(name):
    CACHE.mkdir(parents=True, exist_ok=True)
    path = CACHE / name
    if not path.exists():
        url = f'https://raw.githubusercontent.com/PokeAPI/pokeapi/{REVISION}/data/v2/csv/{name}'
        with urlopen(Request(url, headers={'User-Agent':'PokeVault-data-builder'}), timeout=120) as response:
            path.write_bytes(response.read())
    return csv.DictReader(io.StringIO(path.read_text(encoding='utf-8')))

def clean(text):
    # A soft hyphen (U+00AD) marks a word split across lines in the source
    # ("moun­\ntains"): join the word instead of leaving a space.
    text = re.sub('­\\s*', '', text)
    # A hard hyphen at a line break belongs to a compound word ("bluish-\nwhite").
    text = re.sub(r'(?<=\w)-[\n\f\r]+(?=\w)', '-', text)
    return ' '.join(text.split())

def main():
    versions = {r['id']:r['identifier'].replace('-','') for r in rows('versions.csv')}
    texts = {game:[None]*(maximum+1) for game,maximum in GAMES.items()}
    spanish = {game:[None]*(MAX_SPECIES+1) for game in SPANISH_GAMES}
    for row in rows('pokemon_species_flavor_text.csv'):
        game=versions.get(row['version_id']); species=int(row['species_id'])
        language={'7':'es','9':'en'}.get(row['language_id'])
        if not language:
            continue
        if language=='es' and game in spanish and 1 <= species <= MAX_SPECIES:
            spanish[game][species]=clean(row['flavor_text'])
        if game not in GAMES or not 1 <= species <= GAMES[game]:
            continue
        entry=texts[game][species] or {}
        entry[language]=clean(row['flavor_text'])
        texts[game][species]=entry
    for game,maximum in GAMES.items():
        assert all(texts[game][n] and texts[game][n].get('en') for n in range(1,maximum+1)), game
        assert not any(texts[game][n].get('es') for n in range(1,maximum+1)), f'{game}: exact Spanish text appeared; prefer it'
        for n in range(1,maximum+1):
            source=next((g for g in SPANISH_FROM[game] if spanish[g][n]), None)
            assert source, f'{game} #{n}: no Spanish text in {SPANISH_FROM[game]}'
            texts[game][n]['esFrom']=source
    for game,values in spanish.items():
        used={n for g,m in GAMES.items() for n in range(1,m+1) if texts[g][n]['esFrom']==game}
        spanish[game]=[values[n] if n in used else None for n in range(len(values))]
    assert not any('­' in t for g in texts.values() for e in g if e for t in e.values())
    output='// Generated by scripts/build-pokedex.py; PokeAPI '+REVISION+'. See docs/POKEDEX.md.\n'
    output+='export const DEX_TEXTS='+json.dumps(texts,ensure_ascii=False,separators=(',',':'))+';\n'
    output+='// Spanish text of later official games, keyed by PokeAPI version identifier.\n'
    output+='export const DEX_SPANISH='+json.dumps(spanish,ensure_ascii=False,separators=(',',':'))+';\n'
    ROOT.joinpath('dist/pokedex-data.js').write_text(output,encoding='utf-8',newline='\n')
    print(f'Generated descriptions for {len(GAMES)} games; Spanish from {", ".join(SPANISH_GAMES)}.')

if __name__ == '__main__':
    main()
